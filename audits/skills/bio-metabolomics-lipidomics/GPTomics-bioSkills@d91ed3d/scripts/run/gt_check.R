suppressMessages(library(lipidr))
raw <- read.csv("../data/synthetic_lipidomics_intensities.csv", check.names = FALSE)
d <- as_lipidomics_experiment(raw)
d <- suppressWarnings(add_sample_annotation(d, "../data/synthetic_sample_annotation.csv"))
d_istd <- normalize_istd(d, measure = "Area", exclude = "blank", log = TRUE)
de_results <- suppressWarnings(de_analysis(d_istd, Disease - Control, measure = "Area"))
sig <- significant_molecules(de_results, p.cutoff = 0.05, logFC.cutoff = 1)
sig_vec <- sig[[1]]
cat("Significant (>2FC, adj.P<0.05):", paste(sig_vec, collapse=", "), "\n")
planted_up   <- c("PC 34:1", "PC 36:2")
planted_down <- c("PE 36:2")
planted_flat <- c("PC 32:0", "PC 16:0/18:1", "PE 34:1", "TG 54:4", "LPC 16:0")
cat("Planted UP (>2FC) recovered:", paste(intersect(planted_up, sig_vec), collapse=", "), "/", length(planted_up), "\n")
cat("Planted DOWN recovered:", paste(intersect(planted_down, sig_vec), collapse=", "), "/", length(planted_down), "\n")
cat("False positives among flat lipids:", length(intersect(planted_flat, sig_vec)), "(expect 0)\n")
