library(GenomicSEM)
b <- deparse(body(userGWAS))
cat("userGWAS length:", length(b), "\n")
idx <- grep("estimator = \"DWLS\"|estimator=\"DWLS\"", b)
cat("Hard-coded DWLS estimator calls (regardless of `estimation` arg):\n")
for (i in idx) cat(i, ": ", b[i], "\n")
idx2 <- grep("estimator = estimation|estimator=estimation", b)
cat("\nCalls using the user's chosen `estimation`:\n")
for (i in idx2) cat(i, ": ", b[i], "\n")

cat("\n--- Same check for commonfactorGWAS ---\n")
