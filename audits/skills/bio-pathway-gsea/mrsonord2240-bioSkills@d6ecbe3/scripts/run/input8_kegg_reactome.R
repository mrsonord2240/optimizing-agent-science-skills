library(clusterProfiler)
library(ReactomePA)
library(org.Hs.eg.db)
set.seed(20260923)
ids <- head(keys(org.Hs.eg.db, keytype="ENTREZID"), 4000)
gl <- setNames(rnorm(length(ids)), ids)
gl <- sort(gl, decreasing=TRUE)
kegg <- gseKEGG(geneList=gl, organism="hsa", keyType="ncbi-geneid", minGSSize=10, maxGSSize=500, eps=0, pvalueCutoff=1, seed=TRUE, verbose=FALSE)
react <- gsePathway(geneList=gl, organism="human", minGSSize=10, maxGSSize=500, eps=0, pvalueCutoff=1, seed=TRUE, verbose=FALSE)
kt <- as.data.frame(kegg); rt <- as.data.frame(react)
stopifnot(is.data.frame(kt), is.data.frame(rt), all(c("NES","p.adjust") %in% names(kt)), all(c("NES","p.adjust") %in% names(rt)))
write.csv(kt,"F:/OpenScience/audits/bio-pathway-gsea/data/input8_kegg.csv",row.names=FALSE)
write.csv(rt,"F:/OpenScience/audits/bio-pathway-gsea/data/input8_reactome.csv",row.names=FALSE)
cat(sprintf("ASSERT input8 kegg_terms=%d reactome_terms=%d\n",nrow(kt),nrow(rt)))
