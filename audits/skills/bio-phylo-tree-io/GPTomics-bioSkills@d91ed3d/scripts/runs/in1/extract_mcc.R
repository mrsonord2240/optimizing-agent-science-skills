# Input 1 (Canonical), R route from SKILL.md: treeio read.beast -> get.data()/as_tibble(); write.beast round trip.
# Data are SYNTHETIC (data/mcc6.tree).
suppressPackageStartupMessages({library(treeio); library(ape); library(tidytree)})
cat("treeio", as.character(packageVersion("treeio")), "ape", as.character(packageVersion("ape")), "\n")
mcc <- "../../data/mcc6.tree"
b <- read.beast(mcc)
d <- get.data(b)
cat("get.data columns:", paste(names(d), collapse = ", "), "\n")
cat("has height_0.95_HPD:", "height_0.95_HPD" %in% names(d), "\n")
cat("class of height_0.95_HPD column:", class(d[["height_0.95_HPD"]]), "\n")
tb <- as_tibble(b)
nd <- tb[!is.na(tb$posterior), c("node", "label", "posterior", "height", "height_0.95_HPD")]
nd$hpd_lo <- sapply(nd[["height_0.95_HPD"]], `[`, 1)
nd$hpd_hi <- sapply(nd[["height_0.95_HPD"]], `[`, 2)
print(as.data.frame(nd[, c("node", "posterior", "height", "hpd_lo", "hpd_hi")]))
write.beast(b, file = "mcc6_writebeast.tree")
b2 <- read.beast("mcc6_writebeast.tree")
d2 <- get.data(b2)
cat("write.beast round-trip columns:", paste(names(d2), collapse = ", "), "\n")
m <- merge(as_tibble(b)[, c("label", "posterior")], as_tibble(b2)[, c("label", "posterior")], by = "label")
cat("tips posterior compare rows:", nrow(m), "\n")
p1 <- sort(na.omit(as.numeric(d$posterior))); p2 <- sort(na.omit(as.numeric(d2$posterior)))
cat("posteriors identical after round trip:", identical(p1, p2), "\n")
h1 <- sort(unlist(d[["height_0.95_HPD"]])); h2 <- sort(unlist(d2[["height_0.95_HPD"]]))
cat("HPD values identical after round trip:", isTRUE(all.equal(as.numeric(h1), as.numeric(h2))), "\n")
cat("isRooted(read.beast phylo):", is.rooted(as.phylo(b)), "\n")
a <- read.nexus(mcc)
cat("ape::read.nexus class:", class(a), " node.label:", paste(a$node.label, collapse = ","), " tips:", paste(a$tip.label, collapse = ","), "\n")
write.tree(a, "ape_writetree.nwk")
cat("ape write.tree output:", readLines("ape_writetree.nwk"), "\n")
