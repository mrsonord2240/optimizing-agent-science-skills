withCallingHandlers({ png(tempfile(fileext=".png"), 500, 400); print(pi2); dev.off() }, warning = function(w) { cat("DENSE Inf WARNING at draw:", conditionMessage(w), "\n"); invokeRestart("muffleWarning") })
