# Skill's OUTRIDER code path on OUTRIDER's OWN simulator (makeExampleOutriderDataSet) at several cohort sizes (SYNTHETIC).
suppressPackageStartupMessages(library(OUTRIDER)); library(BiocParallel)
a <- commandArgs(TRUE); m <- as.integer(a[1]); n <- as.integer(a[2])
set.seed(42)
ods0 <- makeExampleOutriderDataSet(n = n, m = m, freq = 1e-3)
truth <- assay(ods0, "trueOutliers"); ntrue <- sum(truth != 0)
cnt <- counts(ods0); ods <- OutriderDataSet(countData = cnt)
ods <- filterExpression(ods, minCounts = TRUE, filterGenes = TRUE)
q_best <- estimateBestQ(ods)
ods <- OUTRIDER(ods, q = q_best, BPPARAM = SerialParam())
res <- results(ods, padjCutoff = 0.05, zScoreCutoff = 0)
tk <- which(truth != 0, arr.ind = TRUE)
hit <- paste(rownames(truth)[tk[, 1]], colnames(truth)[tk[, 2]]) %in% paste(res$geneID, res$sampleID)
cat(sprintf("m=%d samples n=%d genes: q=%d injected=%d detected=%d/%d total calls=%d false calls=%d\n", m, n, q_best, ntrue, sum(hit), ntrue, nrow(res), nrow(res) - sum(hit)))
