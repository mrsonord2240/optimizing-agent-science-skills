# OURS request 1: same question. Follows OUR SKILL.md "Single-Mediator Observational with Sensitivity" as written
# (sims=5000, boot.ci.type='bca', medsens rho.by=0.05 sims=1000), then applies OUR Common Errors fix if it errors.
source('F:/OpenScience/comparisons/mediation-same-id/run/common.R')
suppressMessages(library(mediation)); cat('mediation', as.character(packageVersion('mediation')), '\n')
dat <- read.csv(file.path(D, 'A_planted.csv'))
set.seed(1)
med_model <- lm(expression ~ genotype + age + sex + pc1 + pc2, data = dat)
out_model <- glm(disease ~ genotype + expression + age + sex + pc1 + pc2, data = dat, family = binomial)
med_result <- try_run('mediate boot bca sims=5000', mediate(med_model, out_model, treat = 'genotype', mediator = 'expression', boot = TRUE, sims = 5000, boot.ci.type = 'bca'))
cat('ACME', round(med_result$d0, 4), 'CI', round(med_result$d0.ci, 4), '\nADE', round(med_result$z0, 4), '\nTotal', round(med_result$tau.coef, 4), '\nPM', round(med_result$n0, 3), '\n')
cat('truth (prob scale):', unlist(truth$A$prob_scale), '\n')
cat('--- as-written sensitivity on the logit/boot object ---\n')
sens <- try_run('medsens as written', medsens(med_result, rho.by = 0.05, effect.type = 'indirect', sims = 1000))
if (!is.null(sens)) print(summary(sens))
cat('--- OUR Common Errors fix: probit outcome refit ---\n')
out_probit <- glm(disease ~ genotype + expression + age + sex + pc1 + pc2, data = dat, family = binomial(link = 'probit'))
mp <- try_run('mediate probit', mediate(med_model, out_probit, treat = 'genotype', mediator = 'expression', boot = TRUE, sims = 1000))
cat('probit ACME', round(mp$d0, 4), 'CI', round(mp$d0.ci, 4), '\n')
sens2 <- try_run('medsens probit', medsens(mp, rho.by = 0.05, effect.type = 'indirect', sims = 1000))
if (!is.null(sens2)) print(summary(sens2))
# continuous outcome
om <- lm(y_cont ~ genotype + expression + age + sex + pc1 + pc2, data = dat)
r2 <- try_run('continuous mediate', mediate(med_model, om, treat = 'genotype', mediator = 'expression', boot = TRUE, sims = 1000))
cat('continuous: ACME', round(r2$d0, 4), 'CI', round(r2$d0.ci, 4), 'ADE', round(r2$z0, 4), 'PM', round(r2$n0, 3), '| truth ACME 0.30 ADE 0.20 PM 0.60\n')
stopifnot(!is.null(med_result), med_result$d0.ci[1] < 0.105, med_result$d0.ci[2] > 0.105); cat('ASSERT pass: binary ACME CI covers 0.105\n')
stopifnot(r2$d0.ci[1] < 0.30, r2$d0.ci[2] > 0.30); cat('ASSERT pass: continuous ACME CI covers 0.30\n')
